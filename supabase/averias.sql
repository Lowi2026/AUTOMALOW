-- Crea/migra public.averias para guardar cada índice en su propia columna.
-- Ejecutar desde Supabase > SQL Editor. Migra automáticamente pasos desde
-- la versión anterior de la tabla, donde se almacenaban juntos en un jsonb.
create table if not exists public.averias (
    id bigint generated by default as identity primary key,
    orden integer not null unique,
    label text not null,
    grupo integer,
    tipo integer,
    subtipo_l1 integer,
    subtipo_l2 integer,
    extra_cierre integer,
    activo boolean not null default true
);

alter table public.averias
    add column if not exists grupo integer,
    add column if not exists tipo integer,
    add column if not exists subtipo_l1 integer,
    add column if not exists subtipo_l2 integer,
    add column if not exists extra_cierre integer;

-- Conserva los valores ya editados en columnas; solo completa valores nulos.
do $$
begin
    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'averias'
          and column_name = 'pasos'
    ) then
        execute $migration$
            update public.averias
            set grupo = coalesce(grupo, (pasos ->> 'GRUPO')::integer),
                tipo = coalesce(tipo, (pasos ->> 'TIPO')::integer),
                subtipo_l1 = coalesce(subtipo_l1, (pasos ->> 'SUBTIPO_L1')::integer),
                subtipo_l2 = coalesce(subtipo_l2, (pasos ->> 'SUBTIPO_L2')::integer),
                extra_cierre = coalesce(extra_cierre, (pasos ->> 'EXTRA_CIERRE')::integer)
            where grupo is null
               or tipo is null
               or subtipo_l1 is null
               or subtipo_l2 is null
               or extra_cierre is null
        $migration$;

        alter table public.averias drop column pasos;
    end if;
end
$$;

alter table public.averias
    alter column grupo set not null,
    alter column tipo set not null,
    alter column subtipo_l1 set not null,
    alter column subtipo_l2 set not null,
    alter column extra_cierre set not null;

alter table public.averias enable row level security;
grant select on public.averias to anon, authenticated;

drop policy if exists "Lectura pública de averías activas" on public.averias;
create policy "Lectura pública de averías activas"
    on public.averias
    for select
    to anon, authenticated
    using (activo = true);

